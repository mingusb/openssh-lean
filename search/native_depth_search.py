DESTINATION = '{destination}'


def packed(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False)


def atomic_json(path, value):
    """Publish one complete JSON document or leave the previous one intact."""
    path = Path(path)
    temporary = path.with_name('.'+path.name+'.pending-'+uuid.uuid4().hex)
    try:
        with temporary.open('x', encoding='utf-8') as stream:
            stream.write(packed(value)+'\n')
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def atomic_bytes(path, value, mode=0o644):
    """Publish complete generated bytes without exposing a partial script."""
    path = Path(path)
    temporary = path.with_name('.'+path.name+'.pending-'+uuid.uuid4().hex)
    try:
        with temporary.open('xb') as stream:
            stream.write(value)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.chmod(mode)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def ensure_reproducer_runtime(result, result_path, marker):
    """Pin current tooling only before insertion of a catalog reproducer."""
    if marker.exists():
        need(type(result.get('reproducer_runtime')) is dict,
             'Cataloged search result lacks its pinned replay runtime')
        return
    runtime = dict(
        stack_limit_kib=subprocess.check_output(
            ['/usr/bin/bash', '-c', 'ulimit -s'], text=True).strip(),
        trace_parser_sha256=sha(WORKSPACE/'search/native_signal_replay.py'))
    if 'reproducer_runtime' in result:
        need(result['reproducer_runtime'] == runtime,
             'Resume stack limit or native trace parser changed')
    else:
        result['reproducer_runtime'] = runtime
        atomic_json(result_path, result)


def decode(name, value):
    need(type(value) is str, name+' must be base64 text')
    try:
        return base64.b64decode(value, validate=True)
    except (binascii.Error, ValueError) as error:
        raise ValueError(name+' is not valid base64') from error


def check_profile(raw):
    """Validate only strategy inputs; the archive validates target identity."""
    need(type(raw) is dict and raw.get('schema') == 1,
         'Expected native depth profile schema 1')
    target = raw.get('target')
    argv = raw.get('argv')
    need(type(target) is str and target and
         type(argv) is list and all(type(arg) is str and '\0' not in arg for arg in argv),
         'Target and argv must be nonempty valid strings')
    occurrences = sum(arg.count(DESTINATION) for arg in argv)
    need(occurrences in (0, 1), 'Use the destination token at most once')
    prefix = decode('prefix_base64', raw.get('prefix_base64', ''))
    record = decode('record_base64', raw.get('record_base64'))
    suffix = decode('suffix_base64', raw.get('suffix_base64', ''))
    need(record, 'The repeated record must be nonempty')
    environment = raw.get('env', DEFAULT_ENV)
    need(type(environment) is dict and all(type(k) is str and type(v) is str and
         k and '=' not in k and '\0' not in k and '\0' not in v
         for k, v in environment.items()), 'Invalid exact environment')
    cwd = Path(raw.get('cwd', WORKSPACE/'work/reference-source'))
    need(cwd.is_absolute() and cwd.is_dir(), 'cwd must be an existing absolute directory')
    expected = raw.get('expect_signal')
    need(type(expected) is str and expected in signal.Signals.__members__,
         'expect_signal must name an OS signal')
    expected = signal.Signals[expected].name
    initial = raw.get('initial_depth', 1)
    growth = raw.get('growth_factor', 2)
    repetitions = raw.get('confirmation_runs', 3)
    maximum = raw.get('max_depth')
    timeout = raw.get('timeout_seconds')
    mode = raw.get('mode', 'doubling')
    observation_mode = raw.get('observation_mode', 'direct')
    need(type(initial) is int and initial > 0 and type(growth) is int and growth >= 2 and
         type(repetitions) is int and repetitions >= 2,
         'Initial depth, growth factor, and confirmation runs are invalid')
    need(maximum is None or (type(maximum) is int and maximum >= initial),
         'max_depth, when given, must be at least initial_depth')
    need(timeout is None or (type(timeout) in (int, float) and timeout > 0),
         'timeout_seconds, when given, must be positive')
    need(mode in ('doubling', 'sequential'),
         'mode must be doubling or sequential')
    need(observation_mode in ('direct', 'process_family'),
         'observation_mode must be direct or process_family')
    core_link = raw.get('core_link')
    if core_link is not None:
        required = {'section', 'ordinal', 'address', 'site_kind',
                    'core_site_sha256', 'source_file', 'source_line',
                    'source_sha256', 'relation'}
        optional = {'fatal_pid', 'recursive_symbol', 'min_recursive_frames'}
        need(type(core_link) is dict and required <= core_link.keys() and
             core_link.keys() <= required | optional,
             'core_link has missing or unsupported catalog fields')
        need(expected == 'SIGSEGV',
             'The native-Core link API currently requires SIGSEGV')
    return dict(schema=1, target=target, argv=argv, cwd=str(cwd.resolve()),
                env=environment, expect_signal=expected, initial_depth=initial,
                growth_factor=growth, confirmation_runs=repetitions,
                max_depth=maximum, timeout_seconds=timeout,
                mode=mode, observation_mode=observation_mode,
                prefix_base64=base64.b64encode(prefix).decode(),
                record_base64=base64.b64encode(record).decode(),
                suffix_base64=base64.b64encode(suffix).decode(),
                core_link=core_link)


def profile_bytes(profile):
    return tuple(decode(name, profile[name]) for name in
                 ('prefix_base64', 'record_base64', 'suffix_base64'))


def protocol_input(parts, depth):
    need(type(depth) is int and depth >= 0, 'Depth must be nonnegative')
    prefix, record, suffix = parts
    return prefix + record*depth + suffix


def write_protocol(stream, parts, depth, *, rewind=True):
    """Stream one repeated input with memory independent of its depth."""
    need(type(depth) is int and depth >= 0, 'Depth must be nonnegative')
    prefix, record, suffix = parts
    digest = hashlib.sha256()
    total = 0

    def write(chunk):
        nonlocal total
        stream.write(chunk)
        digest.update(chunk)
        total += len(chunk)

    write(prefix)
    records_per_chunk = max(1, 65536//len(record))
    chunk = record*records_per_chunk
    remaining = depth
    while remaining >= records_per_chunk:
        write(chunk)
        remaining -= records_per_chunk
    if remaining:
        write(record*remaining)
    write(suffix)
    stream.flush()
    if rewind:
        stream.seek(0)
    return total, digest.hexdigest()


def expanded_argv(template, destination):
    if destination is None:
        need(all(DESTINATION not in arg for arg in template),
             'A destination token requires an isolated directory')
        return list(template)
    return [arg.replace(DESTINATION, str(destination)) for arg in template]


def cleanup_fresh_tree(root):
    """Remove only a directory allocated by this strategy under /tmp."""
    root = Path(root)
    need(root.parent == Path('/tmp') and root.name.startswith('openssh-depth-') and
         root.is_dir() and not root.is_symlink() and root.resolve() == root,
         'Refusing to remove an unrecognized probe directory')
    subprocess.run(['/usr/bin/rm', '-rf', '--', str(root)], check=True)


def returncode_signal(returncode):
    if returncode is None or returncode >= 0:
        return None
    try:
        return signal.Signals(-returncode).name
    except ValueError:
        return 'UNKNOWN_'+str(-returncode)


def run_isolated_process(command, protocol, cwd, env, timeout):
    """Keep descendants in one process group; kill that group on timeout."""
    process = subprocess.Popen(command, stdin=protocol, cwd=cwd, env=env,
                               stdout=subprocess.DEVNULL,
                               stderr=subprocess.DEVNULL,
                               start_new_session=True)
    try:
        return process.wait(timeout=timeout), False
    except BaseException as error:
        # The session is private to this probe. Keep the leader unreaped until
        # after killpg, preventing its process-group ID from being recycled.
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        process.wait()
        if isinstance(error, subprocess.TimeoutExpired):
            return None, True
        raise


class NativeDepthSearch:
    def __init__(self, profile, program, binary_sha256, output, *,
                 resume=False, profile_source_sha256=None,
                 archive_manifest_sha256=None, catalog_dir=DEFAULT_CATALOG):
        self.profile = check_profile(profile)
        self.program = Path(program).resolve(strict=True)
        need(sha(self.program) == binary_sha256, 'Pinned native binary changed')
        self.binary_sha256 = binary_sha256
        self.trace_tool = None
        if self.profile['observation_mode'] == 'process_family':
            found = shutil.which('strace')
            need(found is not None, 'Process-family probing requires strace')
            self.trace_tool = Path(found).resolve(strict=True)
        self.output = Path(output).resolve()
        self.parts = profile_bytes(self.profile)
        self.cache = {}
        self.next_sequence = 0
        self.events = self.output/'probes.jsonl'
        self.identity = dict(schema=1, target=self.profile['target'],
                             normalized_profile_sha256=hashlib.sha256(
                                 packed(self.profile).encode()).hexdigest(),
                             profile_source_sha256=profile_source_sha256,
                             binary_path=str(self.program),
                             binary_sha256=binary_sha256,
                             archive_manifest_sha256=archive_manifest_sha256,
                             catalog_dir=str(Path(catalog_dir).resolve()),
                             trace_tool=(dict(path=str(self.trace_tool),
                                              sha256=sha(self.trace_tool))
                                         if self.trace_tool is not None else None))
        if resume:
            need(self.output.is_dir() and not self.output.is_symlink(),
                 'Resume output directory does not exist')
            need(json.loads((self.output/'identity.json').read_bytes()) == self.identity,
                 'Resume profile, archive, or pinned binary identity changed')
            need((self.output/'profile.json').read_text() == packed(self.profile)+'\n',
                 'Resume normalized profile changed')
            self.load_events()
        else:
            self.output.mkdir(parents=True, exist_ok=False)
            atomic_json(self.output/'identity.json', self.identity)
            atomic_json(self.output/'profile.json', self.profile)
            self.events.touch(exist_ok=False)

    def load_events(self):
        """Replay complete durable probes; preserve and discard a torn tail."""
        need(self.events.is_file() and not self.events.is_symlink(),
             'Resume probe log is missing')
        prefix, record, suffix = self.parts
        input_digests = {}
        with self.events.open('rb+') as stream:
            while True:
                offset = stream.tell()
                line = stream.readline()
                if not line:
                    break
                if not line.endswith(b'\n'):
                    orphan = self.output/('probes.partial-tail-'+uuid.uuid4().hex+'.bin')
                    with orphan.open('xb') as preserved:
                        preserved.write(line)
                        preserved.flush()
                        os.fsync(preserved.fileno())
                    stream.truncate(offset)
                    stream.flush()
                    os.fsync(stream.fileno())
                    break
                row = json.loads(line)
                depth = row.get('depth')
                if type(depth) is int and depth >= 0 and depth not in input_digests:
                    with open(os.devnull, 'wb') as sink:
                        input_digests[depth] = write_protocol(
                            sink, self.parts, depth, rewind=False)[1]
                self.next_sequence += 1
                family_terminations = row.get('family_signal_terminations')
                family_deliveries = row.get('family_signal_deliveries')
                valid_family = (
                    type(family_terminations) is list and
                    type(family_deliveries) is list and
                    all(type(item) is str and item in signal.Signals.__members__
                        for item in family_terminations+family_deliveries) and
                    family_terminations == sorted(set(family_terminations)) and
                    family_deliveries == sorted(set(family_deliveries)) and
                    (self.profile['observation_mode'] == 'process_family' or
                     (not family_terminations and not family_deliveries)))
                direct_signal = returncode_signal(row.get('returncode'))
                observed = (not row.get('timed_out') and
                            (direct_signal == self.profile['expect_signal'] or
                             (valid_family and
                              self.profile['expect_signal'] in family_terminations)))
                need(row.get('schema') == 1 and
                     row.get('sequence') == self.next_sequence and
                     type(depth) is int and depth >= 0 and
                     row.get('input_bytes') ==
                     len(prefix)+len(record)*depth+len(suffix) and
                     row.get('input_sha256') == input_digests.get(depth) and
                     type(row.get('elapsed_ns')) is int and row['elapsed_ns'] >= 0 and
                     type(row.get('timed_out')) is bool and
                     row.get('observation_mode') == self.profile['observation_mode'] and
                     valid_family and
                     (row.get('returncode') is None if row['timed_out']
                      else type(row.get('returncode')) is int) and
                     row.get('observed_signal') ==
                     (self.profile['expect_signal'] if observed else direct_signal) and
                     row.get('expected_signal_observed') == observed,
                     'Resume probe record is malformed or changed')
                self.cache.setdefault(depth, []).append(row)

    def probe(self, depth):
        """One native execution. Store its outcome before any next decision."""
        scratch = None
        family_terminations, family_deliveries = [], []
        started = time.perf_counter_ns()
        try:
            with tempfile.TemporaryFile(mode='w+b', dir='/tmp') as protocol:
                input_bytes, input_sha256 = write_protocol(protocol, self.parts, depth)
                needs_destination = any(DESTINATION in arg for arg in self.profile['argv'])
                if needs_destination or self.trace_tool is not None:
                    scratch = Path(tempfile.mkdtemp(prefix='openssh-depth-', dir='/tmp'))
                if needs_destination:
                    destination = scratch/'destination'
                    destination.mkdir()
                else:
                    destination = None
                argv = expanded_argv(self.profile['argv'], destination)
                command = [str(self.program), *argv]
                if self.trace_tool is not None:
                    command = [str(self.trace_tool), '-ff', '-e', 'trace=none',
                               '-e', 'signal=all', '-o', str(scratch/'trace'),
                               '--', *command]
                returncode, timed_out = run_isolated_process(
                    command, protocol, self.profile['cwd'],
                    self.profile['env'], self.profile['timeout_seconds'])
                if self.trace_tool is not None and not timed_out:
                    deliveries, terminations, _ = parse_signal_traces(scratch)
                    family_deliveries = sorted({row['signal'] for row in deliveries})
                    family_terminations = sorted({row['signal'] for row in terminations})
        finally:
            if scratch is not None:
                cleanup_fresh_tree(scratch)
        direct_signal = returncode_signal(returncode)
        expected = self.profile['expect_signal']
        observed = (not timed_out and
                    (direct_signal == expected or expected in family_terminations))
        observed_signal = expected if observed else direct_signal
        record = dict(schema=1, sequence=self.next_sequence+1,
                      depth=depth, returncode=returncode, timed_out=timed_out,
                      observation_mode=self.profile['observation_mode'],
                      observed_signal=observed_signal,
                      family_signal_deliveries=family_deliveries,
                      family_signal_terminations=family_terminations,
                      expected_signal_observed=observed,
                      input_bytes=input_bytes, input_sha256=input_sha256,
                      elapsed_ns=time.perf_counter_ns()-started)
        with self.events.open('a', encoding='utf-8') as stream:
            stream.write(packed(record)+'\n')
            stream.flush()
            os.fsync(stream.fileno())
        self.next_sequence += 1
        self.cache.setdefault(depth, []).append(record)
        return record

    def classify(self, depth, runs):
        rows = self.cache.setdefault(depth, [])
        while len(rows) < runs:
            self.probe(depth)
        subset = rows[:runs]
        if any(row['timed_out'] for row in subset):
            return 'inconclusive_timeout'
        count = sum(row['expected_signal_observed'] for row in subset)
        if count == runs:
            return 'observed_crash'
        if count == 0:
            return 'no_observed_crash'
        return 'mixed'

    def search(self):
        """Doubling is fast for threshold families; sequential checks every depth."""
        profile = self.profile
        repeats = profile['confirmation_runs']
        baseline = self.classify(0, repeats)
        need(baseline != 'inconclusive_timeout', 'Zero-depth probe timed out')
        if baseline == 'observed_crash':
            return dict(status='observed_crash_at_zero_depth', witness_depth=0,
                        observed_noncrashing_depth=None, observed_crash_depth=0,
                        exponential_crash_depth=0, mixed_depths=[],
                        probe_count=sum(map(len, self.cache.values())))
        if baseline == 'mixed':
            return dict(status='mixed_zero_depth_signal', witness_depth=0,
                        observed_noncrashing_depth=None, observed_crash_depth=0,
                        exponential_crash_depth=None, mixed_depths=[0],
                        probe_count=sum(map(len, self.cache.values())))
        if profile['mode'] == 'sequential':
            return self.search_sequential()
        return self.search_doubling()

    def search_sequential(self):
        """Inspect each depth; no threshold or monotonicity assumption."""
        profile = self.profile
        repeats = profile['confirmation_runs']
        depth = profile['initial_depth']
        observed_noncrash = 0
        mixed = []
        while True:
            maximum = profile['max_depth']
            if maximum is not None and depth > maximum:
                return dict(status='no_crash_observed_through_profile_maximum',
                            max_depth=maximum, search_mode='sequential',
                            mixed_depths=mixed,
                            probe_count=sum(map(len, self.cache.values())))
            outcome = self.classify(depth, repeats)
            need(outcome != 'inconclusive_timeout',
                 'Native depth probe timed out at depth '+str(depth))
            if outcome == 'observed_crash':
                return dict(status='observed_depth_bracket', witness_depth=depth,
                            observed_noncrashing_depth=observed_noncrash,
                            observed_crash_depth=depth,
                            exponential_crash_depth=None, mixed_depths=mixed,
                            search_mode='sequential',
                            probe_count=sum(map(len, self.cache.values())))
            if outcome == 'no_observed_crash':
                observed_noncrash = depth
            else:
                mixed.append(depth)
            depth += 1

    def search_doubling(self):
        """O(log depth) probes if repeated-record faults have a threshold."""
        profile = self.profile
        repeats = profile['confirmation_runs']
        depth = profile['initial_depth']
        maximum = profile['max_depth']
        while True:
            if maximum is not None and depth > maximum:
                return dict(status='no_crash_observed_through_profile_maximum',
                            max_depth=maximum,
                            search_mode='doubling',
                            probe_count=sum(map(len, self.cache.values())))
            first = self.classify(depth, 1)
            need(first != 'inconclusive_timeout',
                 'Native depth probe timed out at depth '+str(depth))
            if first == 'observed_crash':
                classification = self.classify(depth, repeats)
                need(classification != 'inconclusive_timeout',
                     'Native depth confirmation timed out at depth '+str(depth))
                if classification == 'observed_crash':
                    exponential_high = depth
                    break
            following = depth*profile['growth_factor']
            depth = (maximum if maximum is not None and
                     depth < maximum < following else following)
        low, high = 0, exponential_high
        mixed = []
        # Confirm the best previously inspected noncrashing depth before bisection.
        for candidate in sorted((d for d in self.cache if 0 < d < high), reverse=True):
            outcome = self.classify(candidate, repeats)
            need(outcome != 'inconclusive_timeout',
                 'Native depth confirmation timed out at depth '+str(candidate))
            if outcome == 'no_observed_crash':
                low = candidate
                break
            if outcome == 'mixed':
                mixed.append(candidate)
        while low + 1 < high:
            mid = (low + high)//2
            outcome = self.classify(mid, repeats)
            need(outcome != 'inconclusive_timeout',
                 'Native depth confirmation timed out at depth '+str(mid))
            if outcome == 'observed_crash':
                high = mid
            elif outcome == 'no_observed_crash':
                low = mid
            else:
                mixed.append(mid)
                break
        return dict(status='observed_depth_bracket', witness_depth=exponential_high,
                    observed_noncrashing_depth=low, observed_crash_depth=high,
                    exponential_crash_depth=exponential_high,
                    mixed_depths=sorted(set(mixed)),
                    search_mode='doubling',
                    probe_count=sum(map(len, self.cache.values())))

    def capture(self, depth, catalog_dir=DEFAULT_CATALOG):
        """Turn the chosen native invocation into a verified immutable receipt."""
        destination = None
        if any(DESTINATION in arg for arg in self.profile['argv']):
            destination = self.output/'capture-destination'
            marker = self.output/'capture-destination.owner'
            marker_text = self.identity['normalized_profile_sha256']+'\n'
            if destination.exists():
                need(marker.is_file() and marker.read_text() == marker_text and
                     destination.resolve().parent == self.output and
                     not destination.is_symlink(),
                     'Refusing to reuse an unrecognized capture destination')
                subprocess.run(['/usr/bin/rm', '-rf', '--', str(destination)], check=True)
            else:
                need(not marker.exists() or marker.read_text() == marker_text,
                     'Capture ownership marker differs')
                marker.write_text(marker_text)
            destination.mkdir()
        recipe = dict(schema=1, target=self.profile['target'],
                      argv=expanded_argv(self.profile['argv'], destination),
                      cwd=self.profile['cwd'], env=self.profile['env'],
                      stdin_base64=base64.b64encode(protocol_input(self.parts, depth)).decode(),
                      expect_signal=self.profile['expect_signal'],
                      timeout_seconds=self.profile['timeout_seconds'])
        atomic_json(self.output/'receipt-recipe.json', recipe)
        try:
            summary = replay_recipe(recipe, catalog_dir=catalog_dir,
                                    trace_signals=True, capture_crash_site=True)
        finally:
            if destination is not None and destination.exists():
                need(destination.resolve().parent == self.output and
                     not destination.is_symlink(), 'Capture destination escaped output')
                subprocess.run(['/usr/bin/rm', '-rf', '--', str(destination)], check=True)
                destination.mkdir()
        need(summary['expected_observed'] and not summary['timed_out'] and
             any(site.get('status') == 'captured' and
                 site.get('signal') == self.profile['expect_signal']
                 for site in summary['primary_sites']),
             'Selected depth did not yield a decoded fatal native signal')
        return dict(id=summary['id'], receipt=summary['receipt'],
                    receipt_sha256=summary['receipt_sha256'],
                    primary_sites=summary['primary_sites'])


def run_profile(profile_path, output, catalog_dir=DEFAULT_CATALOG, *, resume=False):
    profile_path = Path(profile_path).resolve(strict=True)
    profile = check_profile(json.loads(profile_path.read_bytes()))
    archive = Archive(WORKSPACE/'local/models/current')
    program, binary_digest, _ = native_binary(archive, profile['target'])
    output = Path(output).resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    catalog_dir = Path(catalog_dir).resolve()
    lock_path = output.parent/('.'+output.name+'.depth-search.lock')
    with lock_path.open('a+') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as error:
            raise RuntimeError('Native depth output is already being searched') from error
        campaign = NativeDepthSearch(
            profile, program, binary_digest, output, resume=resume,
            profile_source_sha256=sha(profile_path),
            archive_manifest_sha256=archive.manifest_sha256,
            catalog_dir=catalog_dir)
        result_path = campaign.output/'search-result.json'
        identity_fields = dict(profile_sha256=sha(profile_path),
                               target=profile['target'],
                               native_binary_sha256=binary_digest,
                               native_binary=str(program),
                               output=str(campaign.output),
                               catalog_dir=str(catalog_dir))
        if resume and result_path.exists():
            need(result_path.is_file() and not result_path.is_symlink(),
                 'Resume result is not a regular file')
            result = json.loads(result_path.read_bytes())
            need(all(result.get(key) == value for key, value in identity_fields.items()),
                 'Resume result identity differs from profile or pinned binary')
        else:
            result = campaign.search()
            result.update(identity_fields)
            atomic_json(result_path, result)
        if 'witness_depth' in result:
            if 'receipt' in result:
                saved = result['receipt']
                verified = verify_receipt(saved['receipt'], saved['receipt_sha256'])
                need(verified['id'] == saved['id'] and
                     verified['observation']['primary_sites'] == saved['primary_sites'],
                     'Resumed native receipt differs from recorded search result')
            else:
                prefix, record, suffix = campaign.parts
                result['capture_input_materialized_bytes'] = (
                    len(prefix)+len(record)*result['witness_depth']+len(suffix))
                result['capture_input_memory_scope'] = (
                    'Only probes stream in bounded memory; schema-1 receipt capture '
                    'materializes the selected input')
                atomic_json(result_path, result)
                result['receipt'] = campaign.capture(result['witness_depth'], catalog_dir)
                atomic_json(result_path, result)
            if profile['core_link'] is not None:
                sites = [site for site in result['receipt']['primary_sites']
                         if site.get('status') == 'captured' and
                         site.get('signal') == profile['expect_signal'] and
                         str(site.get('si_code', '')).startswith('SEGV_')]
                need(len(sites) == 1,
                     'Automatic native-Core linkage needs one synchronous fatal site')
                selected = sites[0]
                spec = dict(profile['core_link'],
                            receipt=result['receipt']['receipt'],
                            receipt_sha256=result['receipt']['receipt_sha256'],
                            stable_site_key=selected['stable_site_key'],
                            target=profile['target'])
                if 'native_core_link_id' in result:
                    with Catalog(catalog_dir) as catalog:
                        linked = catalog.read_native_core_link(
                            result['native_core_link_id'])
                    need(linked['native']['observation_id'] == result['receipt']['id'] and
                         linked['native']['stable_site_key'] ==
                         selected['stable_site_key'],
                         'Resumed native-Core link differs from receipt')
                else:
                    with Catalog(catalog_dir) as catalog:
                        result['native_core_link_id'] = catalog.add_native_core_link(**spec)
                    atomic_json(campaign.output/'native-core-link-spec.json', spec)
                    atomic_json(result_path, result)
            if profile['expect_signal'] == 'SIGSEGV':
                # The result is frozen after reproducer insertion because the
                # catalog hashes its exact bytes. Keep the catalog id separate.
                script_path = campaign.output/'reproduce.sh'
                marker = campaign.output/'reproducer-catalog.json'
                ensure_reproducer_runtime(result, result_path, marker)
                if not marker.exists():
                    script_bytes = render_reproducer_script(profile, result)
                    if script_path.exists():
                        need(script_path.is_file() and not script_path.is_symlink() and
                             script_path.read_bytes() == script_bytes,
                             'Generated Bash reproducer differs from this search')
                    else:
                        atomic_bytes(script_path, script_bytes, mode=0o755)
                source_links = {}
                core = profile['core_link']
                if (not marker.exists() and core is not None and
                        core['relation'] == 'causal_recursive_call'):
                    source_marker = campaign.output/'source-context-bridge.json'
                    checked_links = ensure_core_cabs_context_bridge(
                        target=profile['target'],
                        source_file=core['source_file'],
                        source_line=core['source_line'],
                        symbol=core['recursive_symbol'],
                        catalog_dir=catalog_dir,
                        section=core['section'],
                        ordinal=core['ordinal'],
                        core_site_sha256=core['core_site_sha256'],
                        site_kind=core['site_kind'])
                    if source_marker.exists():
                        need(source_marker.is_file() and not source_marker.is_symlink(),
                             'Source bridge marker is not a regular file')
                        saved_links = json.loads(source_marker.read_bytes())
                        # Early receipts predate the status field. Their
                        # identities still need to agree with recomputation.
                        need(all(saved_links.get(key) == checked_links.get(key)
                                 for key in ('source_call_witness_id',
                                             'core_cabs_bridge_id')),
                             'Saved source bridge differs from checked source')
                    else:
                        atomic_json(source_marker, checked_links)
                    source_links = checked_links
                with Catalog(catalog_dir) as catalog:
                    if marker.exists():
                        need(marker.is_file() and not marker.is_symlink(),
                             'Reproducer catalog marker is not a regular file')
                        saved_marker = json.loads(marker.read_bytes())
                        linked = catalog.read_native_reproducer(saved_marker['id'])
                        if not script_path.exists():
                            asset = Path(linked['assets']['script']['path'])
                            atomic_bytes(script_path, asset.read_bytes(), mode=0o755)
                        need(script_path.is_file() and not script_path.is_symlink(),
                             'Resumed Bash program is not a regular file')
                        need(linked['assets']['script']['sha256'] == sha(script_path) and
                             linked['assets']['search-result']['sha256'] ==
                             sha(result_path) and
                             linked['assets']['profile']['sha256'] ==
                             sha(profile_path) and
                             linked['native']['observation_id'] ==
                             result['receipt']['id'],
                             'Resumed catalog reproducer differs from the search')
                    else:
                        reproducer_id = catalog.add_native_reproducer(
                            profile=profile_path, search_result=result_path,
                            script=script_path,
                            native_core_link_id=result.get('native_core_link_id'),
                            source_call_witness_id=source_links.get(
                                'source_call_witness_id'),
                            core_cabs_bridge_id=source_links.get(
                                'core_cabs_bridge_id'))
                        atomic_json(marker, dict(id=reproducer_id))
        return result


