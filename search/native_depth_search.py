"""Fast native stdin repetition search with a verified OpenSSH replay handoff.

The search profile supplies a binary record and a pinned OpenSSH target. Each
probe is a fresh native C process. Doubling finds an observed crash depth;
fresh-process confirmations and bisection refine an observed bracket. Neither
the bracket nor a model syntax site proves that other inputs cannot crash.
"""
